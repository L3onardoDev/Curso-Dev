-- TCL - TRANSAÇÕES E INTEGRIDADES
-- 1. Exemplo: TRANSAÇÃO PARA RESOLVER PROBLEMAS
-- SEM TRANSAÇÃO: PARTE PODE PERMANECER GRAVADA
-- COM TRANSAÇÃO: PODE CONFIRMAR TUDO OU DESFAZER TUDO

-- ESTRUTURA DO CONCEITO

START TRANSACTION
-- COMANDOS SQL
-- INSERT, UPDATE, DELETE, SELECT

COMMIT; -- CONFIRMA TODAS AS ALTERAÇÕES
ROLLBACK; -- DESFAZ TODAS AS ALTERAÇÕES

-- 2. Exemplo: COMMIT - COFIRMANDO ALTERAÇÕES REALIZADAS

START TRANSACTION;

UPDATE PRODUTO
SET PRECO = 8.50
WHERE ID_PRODUTO = 1

SELECT * FROM PRODUTO
WHERE ID_PRODUTO = 1;

COMMIT;

-- 3. Exemplo: ROLLBACK - DESFAZER ALTERAÇÕES AINDA NÃO CONFRIMADAS

START TRANSACTION;

UPDATE PRODUTO
SET PRECO = 5000.00
WHERE ID_PRODUTO = 1

SELECT * FROM PRODUTO
WHERE ID_PRODUTO = 1;

ROLLBACK;

-- 4. Exemplo: 

START TRANSACTION;

UPDATE PRODUTO
SET PRECO = PRECO * 1.05
WHERE ID_CATEGORIA = 1

SAVEPOINT REAJUSTE_CAFES;

SELECT * FROM PRODUTO WHERE ID_CATEGORIA = 1;
UPDATE PRODUTO
SET PRECO = PRECO * 1.50
WHERE ID_CATEGORIA = 1;

ROLLBACK TO SAVEPOINT REAJUSTE_CAFES;

COMMIT;

-- 5. Exemplo: RELEASE SAVEPOINT - REMOVER O SAVEPOINT CRIADO ANTERIORMENTE

RELEASE SAVEPOINT REAJUSTE_CAFES;