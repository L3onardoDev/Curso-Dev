-- 16. Funções agregadas — 4 pts
SELECT
COUNT(QUANTIDADE_DISPONIVEL) AS TOTAL_LIVROS, 
SUM(QUANTIDADE_DISPONIVEL) AS SOMA_QUANTIDADE,
AVG(QUANTIDADE_DISPONIVEL) AS MEDIA_QUANTIADE, 
MIN(QUANTIDADE_DISPONIVEL) AS MENOR_QUANTIDADE, 
MAX(QUANTIDADE_DISPONIVEL) AS MAIOR_QUANTIDADE
FROM LIVRO; 

-- 17. INNER JOIN — 4 pts
SELECT E.ID_EMPRESTIMO, U.NOME AS USUARIO, L.TITULO AS LIVRO, E.DATA_EMPRESTIMO, E.STATUS_EMPRESTIMO
FROM EMPRESTIMO E
INNER JOIN USUARIO U 
ON U.ID_USUARIO = E.ID_USUARIO
INNER JOIN LIVRO L 
ON L.ID_LIVRO = E.ID_LIVRO;

-- 18. JOIN + WHERE — 3 pts
SELECT U.NOME, COUNT(E.ID_EMPRESTIMO) AS QTD_EMPRESTIMOS
FROM USUARIO U
INNER JOIN EMPRESTIMO E ON E.ID_USUARIO = U.ID_USUARIO
GROUP BY U.ID_USUARIO, U.NOME
ORDER BY QTD_EMPRESTIMOS DESC;

-- 19. GROUP BY — 4 pts
SELECT U.NOME, COUNT(E.ID_EMPRESTIMO) AS QTD_EMPRESTIMOS
FROM USUARIO U
LEFT JOIN EMPRESTIMO E ON E.ID_USUARIO = U.ID_USUARIO
GROUP BY U.ID_USUARIO, U.NOME
ORDER BY QTD_EMPRESTIMOS DESC;

-- 20. LEFT JOIN — 4 pts
SELECT U.NOME, COUNT(E.ID_EMPRESTIMO) AS QTD_EMPRESTIMOS
FROM USUARIO U
LEFT JOIN EMPRESTIMO E ON E.ID_USUARIO = U.ID_USUARIO
GROUP BY U.ID_USUARIO, U.NOME
ORDER BY QTD_EMPRESTIMOS DESC;

