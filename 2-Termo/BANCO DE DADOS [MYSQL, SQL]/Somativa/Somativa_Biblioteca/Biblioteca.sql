-- 2. Tabela USUARIO — 6 pts
CREATE TABLE USUARIO (
    ID_USUARIO INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(120) NOT NULL UNIQUE,
    TELEFONE VARCHAR(20),
    ATIVO BOOLEAN DEFAULT TRUE
);

-- Tabela LIVRO — 6 pts
CREATE TABLE LIVRO (
    ID_LIVRO INT PRIMARY KEY AUTO_INCREMENT,
    TITULO VARCHAR(150) NOT NULL,
    AUTOR VARCHAR(120) NOT NULL,
    ISBN CHAR(13) NOT NULL UNIQUE,
    ANO_PUBLICACAO INT,
    QUANTIDADE_DISPONIVEL INT NOT NULL DEFAULT 0,
    CONSTRAINT LIVRO_QNTD CHECK (QUANTIDADE_DISPONIVEL >= 0)
);

-- 4. Tabela EMPRESTIMO — 7 pts
CREATE TABLE EMPRESTIMO (
    ID_EMPRESTIMO INT PRIMARY KEY AUTO_INCREMENT,
    DATA_EMPRESTIMO DATETIME DEFAULT CURRENT_TIMESTAMP,
    DATA_PREVISTA DATE NOT NULL,
    DATA_DEVOLUCAO DATE,
    STATUS_EMPRESTIMO VARCHAR(20) DEFAULT 'ABERTO',
    ID_USUARIO INT NOT NULL,
    ID_LIVRO INT NOT NULL,
    CONSTRAINT CK_STATUS_EMPRESTIMO CHECK (STATUS_EMPRESTIMO IN ('ABERTO','DEVOLVIDO', 'ATRASADO')),
    CONSTRAINT FK_EMPRESTIMO_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT FK_EMPRESTIMO_LIVRO FOREIGN KEY (ID_LIVRO)
        REFERENCES LIVRO (ID_LIVRO) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE PAGAMENTO (
    ID_PAGAMENTO INT PRIMARY KEY AUTO_INCREMENT,
    ID_EMPRESTIMO INT NOT NULL,
    DATA_PAGAMENTO DATETIME,
    VALOR DECIMAL(10,2) NOT NULL,
    CONSTRAINT FK_EMPRESTIMO_PAGAMENTO FOREIGN KEY (ID_EMPRESTIMO)
        REFERENCES EMPRESTIMO (ID_EMPRESTIMO)
);

CREATE TABLE ESTOQUE (
    ID_ESTOQUE INT PRIMARY KEY AUTO_INCREMENT,
    PRODUTO VARCHAR(150),
    ENTRADA_PRODUTO DATETIME
);

