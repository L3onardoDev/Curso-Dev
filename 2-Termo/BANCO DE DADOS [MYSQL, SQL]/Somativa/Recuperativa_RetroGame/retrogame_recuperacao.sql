-- 18. INNER JOIN 

SELECT E.ID_LOCACAO, U.NOME AS USUARIO, L.TITULO AS LIVRO, E.DATA_RETIRADA, E.STATUS_LOCACAO
FROM LOCACAO E
INNER JOIN CLIENTE U 
ON U.ID_CLIENTE = E.ID_CLIENTE
INNER JOIN JOGO L 
ON L.ID_JOGO = E.ID_JOGO;

-- 19. JOIN + WHERE 

SELECT * FROM LOCACAO

SELECT U.NOME, COUNT(E.ID_LOCACAO) AS QTD_LOCACOES
FROM CLIENTE U
INNER JOIN LOCACAO E ON E.ID_CLIENTE = U.ID_CLIENTE
GROUP BY U.ID_CLIENTE, U.NOME
ORDER BY QTD_LOCACOES DESC;

-- 20. GROUP BY 

SELECT U.NOME, COUNT(E.ID_LOCACAO) AS QTD_LOCACAO
FROM CLIENTE U
LEFT JOIN LOCACAO E ON E.ID_CLIENTE = U.ID_CLIENTE
GROUP BY U.ID_CLIENTE, U.NOME
ORDER BY QTD_LOCACAO DESC;

-- 21. LEFT JOIN 

SELECT U.NOME, COUNT(E.ID_LOCACAO) AS QTD_LOCACAO
FROM CLIENTE     U
LEFT JOIN LOCACAO E ON E.ID_CLIENTE = U.ID_CLIENTE
GROUP BY U.ID_CLIENTE, U.NOME
ORDER BY QTD_LOCACAO DESC;

